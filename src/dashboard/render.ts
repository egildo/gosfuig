/**
 * Dashboard: a self-contained HTML page that makes the palette — and every
 * accessible foreground/background couple — visible at a glance.
 *
 * Per family:
 *   - a swatch strip (name, hex, lock marker)
 *   - a 12×12 contrast grid: cell[row][col] paints column = background,
 *     row = foreground text, labelled with WCAG ratio + APCA Lc and a pass badge
 *   - the darkest-4-on-lightest-4 contract region is outlined
 *   - a WCAG / APCA / both display toggle
 */
import type { Palette } from '../palette.js';
import type { Family } from '../family.js';
import { contrastMatrix, checkContract, contractRegion, type ContractResult } from '../validate.js';

export function renderDashboard(palette: Palette): string {
  const families = palette.families.map((f) => renderFamily(f, checkContract(f))).join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(palette.name)} — gosfuig palette</title>
<style>${CSS}</style>
</head>
<body data-mode="both">
<header class="top">
  <h1>${esc(palette.name)}</h1>
  <div class="legend">
    <span class="badge aaa">AAA ≥7</span>
    <span class="badge aa">AA ≥4.5</span>
    <span class="badge aal">AA-lg ≥3</span>
    <span class="badge fail">fail</span>
    <span class="spacer"></span>
    <label>show
      <select id="mode" onchange="document.body.dataset.mode=this.value">
        <option value="both">WCAG + APCA</option>
        <option value="wcag">WCAG</option>
        <option value="apca">APCA</option>
      </select>
    </label>
    <label class="chk"><input type="checkbox" id="contract" checked onchange="document.body.classList.toggle('hide-contract',!this.checked)"/> outline contract region</label>
  </div>
</header>
${families}
<footer class="foot">Generated by gosfuig · OKLCH · contract = 4 darkest steps AA on 4 lightest</footer>
</body>
</html>`;
}

function renderFamily(family: Family, contract: ContractResult): string {
  const strip = family.swatches
    .map((s) => {
      const ink = s.oklch.l > 0.6 ? '#000' : '#fff';
      return `<div class="sw" style="background:${s.hex};color:${ink}">
        <span class="nm">${s.name}${s.locked ? ' ★' : ''}</span>
        <span class="hx">${s.hex}</span>
      </div>`;
    })
    .join('');

  const matrix = contrastMatrix(family);
  const region = contractRegion(family.swatches.length);
  const head = `<tr><th class="corner">fg \\ bg</th>${family.swatches
    .map((s) => `<th>${s.name}</th>`)
    .join('')}</tr>`;
  const rows = family.swatches
    .map((fg, r) => {
      const cells = family.swatches
        .map((bg, c) => {
          const v = matrix[r]![c]!;
          const cls = v.wcag >= 7 ? 'aaa' : v.wcag >= 4.5 ? 'aa' : v.wcag >= 3 ? 'aal' : 'fail';
          const contractCell = region.dark.includes(r) && region.light.includes(c) ? ' contract' : '';
          return `<td class="cell ${cls}${contractCell}" style="background:${bg.hex};color:${fg.hex}">
            <span class="aa-sample">Aa</span>
            <span class="metrics"><span class="m-wcag">${v.wcag.toFixed(1)}</span><span class="m-apca">${v.apca.toFixed(0)}</span></span>
          </td>`;
        })
        .join('');
      return `<tr><th class="rowh">${fg.name}</th>${cells}</tr>`;
    })
    .join('');

  const status = contract.passes
    ? `<span class="status ok">contract PASS</span>`
    : `<span class="status bad">contract FAIL — ${contract.failures.length} pair(s) below AA</span>`;
  const worst = `worst ${contract.worst.fg.name}/${contract.worst.bg.name} = ${contract.worst.contrast.wcag.toFixed(2)}`;

  return `<section class="fam">
  <div class="fam-head"><h2>${esc(family.name)}</h2>${status}<span class="worst">${worst}</span></div>
  <div class="strip">${strip}</div>
  <table class="grid">${head}${rows}</table>
</section>`;
}

